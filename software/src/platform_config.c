#include "xgpio_l.h"

void SetResets4DacPll()
{
	XGpio_WriteReg(XPAR_AXI_GPIO_PLL_DAC_BASEADDR,XGPIO_TRI_OFFSET,0<<0 | 0<<1 | 0<<2 | 1<<3 | 1<<4);
	// 0 - RESET - OUTPUT
	// 1 - CLK_SEL0 - OUTPUT
	// 2 - CLK_SEL1 - OUTPUT
	// 3 - STATUS_LD1 - INPUT
	// 4 - STATUS_LD2 - INPUT
	XGpio_WriteReg(XPAR_AXI_GPIO_PLL_DAC_BASEADDR,XGPIO_TRI2_OFFSET,0<<0);
	// 0 - RESET - OUTPUT


	XGpio_WriteReg(XPAR_AXI_GPIO_PLL_DAC_BASEADDR,XGPIO_DATA_OFFSET,0);
	XGpio_WriteReg(XPAR_AXI_GPIO_PLL_DAC_BASEADDR,XGPIO_DATA2_OFFSET,0);
	XGpio_WriteReg(XPAR_AXI_GPIO_PLL_DAC_BASEADDR,XGPIO_DATA_OFFSET,1);
	XGpio_WriteReg(XPAR_AXI_GPIO_PLL_DAC_BASEADDR,XGPIO_DATA2_OFFSET,1);

}
